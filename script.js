// Fungsi Format Harga Singkat (Untuk Kartu)
function formatPriceShort(amountIDR) {
    if (currentCurrency === 'IDR') {
        return (amountIDR / 1000) + 'k';
    }
    const config = currencyConfig[currentCurrency];
    const converted = amountIDR * config.rate;
    return new Intl.NumberFormat(config.locale, {
        style: 'currency',
        currency: config.currency,
        maximumFractionDigits: 0
    }).format(converted);
}

// Fungsi Format Harga Penuh (Untuk Checkout)
function formatPriceFull(amountIDR) {
    const config = currencyConfig[currentCurrency];
    const converted = amountIDR * config.rate;
    return new Intl.NumberFormat(config.locale, {
        style: 'currency',
        currency: config.currency,
        maximumFractionDigits: 0
    }).format(converted);
}

